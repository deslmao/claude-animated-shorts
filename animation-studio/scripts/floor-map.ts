// Floor maps (stage 3C):  npm run floor-map           regenerate src/studio/sets/floor.gen.ts
//                          npm run floor-map -- --check  exit 1 if any set changed since the maps were made
// Builds every set's real geometry in Node (no rendering) and records, on a 0.2 m grid around the set's marks, where
// something stands between knee and head height (walls, props, furniture, posts, trees...). Crowd placement and story
// props use it to stand only on genuinely clear floor; the validator uses it to catch marks / props inside objects.
import "./lib/dom-stub";
import fs from "node:fs";
import * as THREE from "three";
import { SETS } from "../src/studio/sets";
import { LAYOUTS } from "../src/studio/sets/layouts";
import { fnv } from "../src/studio/voice/narration";

const proc = globalThis as unknown as { process: { argv: string[]; exit(n: number): never } };
const CHECK = proc.process.argv.includes("--check"), OUT = "src/studio/sets/floor.gen.ts";
const CELL = 0.2, LO = 0.35, HI = 2.0, MARGIN = 9;

const maps: Record<string, { x0: number; z0: number; w: number; h: number; cell: number; geo: string; rle: string }> = {};
for (const [id, def] of Object.entries(SETS)) {
  const built = def.build(), spots = Object.values(LAYOUTS[id].spots);
  const xs = spots.map((p) => p[0]), zs = spots.map((p) => p[2]);
  const x0 = Math.floor((Math.min(...xs) - MARGIN) / CELL) * CELL, z0 = Math.floor((Math.min(...zs) - MARGIN) / CELL) * CELL;
  const w = Math.ceil((Math.max(...xs) + MARGIN - x0) / CELL), h = Math.ceil((Math.max(...zs) + MARGIN - z0) / CELL);
  const occ = new Uint8Array(w * h);
  let tris = 0, verts = 0;
  const a = new THREE.Vector3(), b = new THREE.Vector3(), c = new THREE.Vector3(), p = new THREE.Vector3();
  built.root.updateMatrixWorld(true);
  built.root.traverse((o) => {
    const m = o as THREE.Mesh;
    if (!m.isMesh) return;
    const pos = m.geometry.attributes.position, idx = m.geometry.index, n = idx ? idx.count : pos.count;
    verts += pos.count;
    for (let i = 0; i < n; i += 3) {
      const ia = idx ? idx.getX(i) : i, ib = idx ? idx.getX(i + 1) : i + 1, ic = idx ? idx.getX(i + 2) : i + 2;
      a.fromBufferAttribute(pos, ia).applyMatrix4(m.matrixWorld); b.fromBufferAttribute(pos, ib).applyMatrix4(m.matrixWorld); c.fromBufferAttribute(pos, ic).applyMatrix4(m.matrixWorld);
      tris++;
      if (Math.max(a.y, b.y, c.y) < LO || Math.min(a.y, b.y, c.y) > HI) continue;
      if (Math.max(a.x, b.x, c.x) < x0 || Math.min(a.x, b.x, c.x) > x0 + w * CELL || Math.max(a.z, b.z, c.z) < z0 || Math.min(a.z, b.z, c.z) > z0 + h * CELL) continue;
      // sample the triangle densely (vertical walls project to lines: sampling handles them like any other)
      const k = Math.max(1, Math.ceil(Math.max(a.distanceTo(b), b.distanceTo(c), c.distanceTo(a)) / (CELL * 0.5)));
      for (let s = 0; s <= k; s++) for (let t = 0; t <= k - s; t++) {
        p.copy(a).addScaledVector(b.clone().sub(a), s / k).addScaledVector(c.clone().sub(a), t / k);
        if (p.y < LO || p.y > HI) continue;
        const gx = Math.floor((p.x - x0) / CELL), gz = Math.floor((p.z - z0) / CELL);
        if (gx >= 0 && gz >= 0 && gx < w && gz < h) occ[gz * w + gx] = 1;
      }
    }
  });
  let rle = "", cur = occ[0], run = 0;
  for (const v of occ) { if (v === cur) run++; else { rle += `${cur ? "o" : "f"}${run}`; cur = v; run = 1; } }
  rle += `${cur ? "o" : "f"}${run}`;
  maps[id] = { x0: +x0.toFixed(2), z0: +z0.toFixed(2), w, h, cell: CELL, geo: fnv(`${tris}:${verts}`), rle };
  const blocked = occ.reduce((s, v) => s + v, 0);
  console.log(`${id.padEnd(10)} ${w}x${h} cells (${(w * CELL).toFixed(1)} x ${(h * CELL).toFixed(1)} m), ${Math.round((100 * blocked) / occ.length)} % occupied, ${tris} triangles`);
}

if (CHECK) {
  const src = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  const stale = Object.entries(maps).filter(([id, m]) => !src.includes(`"${id}":{"x0":${m.x0},"z0":${m.z0},"w":${m.w},"h":${m.h},"cell":${m.cell},"geo":"${m.geo}"`));
  console.log(stale.length ? `floor maps STALE for: ${stale.map(([id]) => id).join(", ")} (run npm run floor-map)` : "floor maps up to date");
  proc.process.exit(stale.length ? 1 : 0);
}
fs.writeFileSync(OUT, `// GENERATED by \`npm run floor-map\` (scripts/floor-map.ts) from the sets' real geometry. Do not edit.
// Per set: a ${CELL} m grid around its marks; "o" = something stands ${LO}-${HI} m above the floor there, "f" = clear floor.
export type FloorMap = { x0: number; z0: number; w: number; h: number; cell: number; geo: string; rle: string };
export const FLOOR_MAPS: Record<string, FloorMap> = ${JSON.stringify(maps)};
`);
console.log(`wrote ${OUT}`);
